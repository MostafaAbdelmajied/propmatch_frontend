/** Fills {{placeholders}} in a mandatory clause body with real header data. */
export function renderMandatoryClauseBody(
  clause: MandatoryClause,
  header: Pick<ContractHeaderData, "propertyAddress" | "rentAmount" | "startDate" | "endDate">,
): string {
  return clause.body
    .replaceAll("{{propertyAddress}}", header.propertyAddress)
    .replaceAll("{{rentAmount}}", formatEGP(header.rentAmount))
    .replaceAll("{{startDate}}", formatDate(header.startDate))
    .replaceAll("{{endDate}}", formatDate(header.endDate));
}
